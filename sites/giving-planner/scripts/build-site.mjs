// Write the Planner's generated public files from site.config.json:
// robots.txt, sitemap.xml, llms.txt, site.webmanifest and _headers (Cloudflare Pages).
//
//   node sites/giving-planner/scripts/build-site.mjs
//
// The partner's origin goes into the CSP (connect-src for its files, frame-src for its
// bridge). Going live: set siteUrl and partner.* to the hosted URLs, put the same partner
// URL in pune_giving_planner.hocon (tools, link_labels) and agent-manifest.json
// (allowed_peers), then run this and `npm run build:planner`.
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const cfg = JSON.parse(await readFile(path.join(root, "site.config.json"), "utf8"));
const site = cfg.siteUrl.replace(/\/$/, "");
const today = new Date().toISOString().slice(0, 10);

const out = {};

out["robots.txt"] = `User-agent: *\nAllow: /\nDisallow: /runtime/\nDisallow: /lib/\n\nSitemap: ${site}/sitemap.xml\n`;

out["sitemap.xml"] = `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${cfg.pages
  .map((p) => `  <url><loc>${site}${p.path}</loc><lastmod>${today}</lastmod><priority>${p.priority.toFixed(1)}</priority></url>`)
  .join("\n")}\n</urlset>\n`;

out["llms.txt"] = `# ${cfg.name}

> ${cfg.description}

${cfg.name} is a small, free planning page and an open agentic website (Open Agentic Web MVP spec 0.3). A donor or CSR team sets a yearly giving total and how many months to spread it over. Its assistant can ask a partner charity's own published agent network what an amount funds. It is not a charity, takes no money and gives no tax advice.

## Facts
- Partner charity: ${cfg.partner.name} (student meal support in Pune), asked through its network at ${cfg.partner.networkUrl}
- The assistant runs in the visitor's browser on the visitor's own AI key. Private details (PAN, phone, email, Aadhaar) are removed on the device before anything is sent.
- Donations happen only on the charity's own website.

## Pages
- [Planner and assistant](${site}/): plan the year, ask the charity
- [Privacy policy](${site}/privacy): what is processed, where, and for how long
- [Terms](${site}/terms): terms of use under Indian law

## Agent files
- [Agent manifest](${site}/agent-manifest.json)
- [Network](${site}/pune_giving_planner.network.json)
`;

out["site.webmanifest"] = JSON.stringify({
  name: cfg.name,
  short_name: "Giving Planner",
  description: cfg.description,
  start_url: "/",
  display: "standalone",
  background_color: "#f3f8fc",
  theme_color: "#0f766e",
  icons: [
    { src: "/icons/icon-192.png", sizes: "192x192", type: "image/png" },
    { src: "/icons/icon-512.png", sizes: "512x512", type: "image/png" },
    { src: "/icons/icon-maskable-512.png", sizes: "512x512", type: "image/png", purpose: "maskable" },
  ],
}, null, 2) + "\n";

const ai = cfg.aiProviders.join(" ");
const p = cfg.partner.origin;
const csp = [
  "default-src 'self'",
  "script-src 'self'",
  // The runtime injects its own stylesheet.
  "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com",
  "font-src https://fonts.gstatic.com",
  "img-src 'self' data:",
  `connect-src 'self' ${p} ${ai}`,
  `frame-src ${p}`,
  "worker-src 'self' blob:",
  "form-action 'self'",
  "frame-ancestors 'none'",
  "base-uri 'self'",
  "object-src 'none'",
  "upgrade-insecure-requests",
].filter((d) => !(d === "upgrade-insecure-requests" && p.startsWith("http://"))).join("; ");

const pub = ["/agent-manifest.json", "/pune_giving_planner.network.json", "/links.json", "/agent-mcp.json", "/.well-known/*"];
out["_headers"] = `# Generated by scripts/build-site.mjs from site.config.json. Do not edit by hand.
/*
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  X-Frame-Options: DENY
  Strict-Transport-Security: max-age=31536000; includeSubDomains
  Cross-Origin-Opener-Policy: same-origin-allow-popups
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=()
  Content-Security-Policy: ${csp}

# Public agent files: other agent sites may read these. CORS only here.
${pub.map((f) => `${f}\n  Access-Control-Allow-Origin: *`).join("\n")}

# Other agent sites load the bridge in a hidden frame.
/bridge/*
  ! X-Frame-Options
  ! Content-Security-Policy
  Content-Security-Policy: default-src 'self'; script-src 'self'; connect-src 'self'; frame-ancestors *; base-uri 'none'; object-src 'none'

/runtime/sandbox-worker.js
  ! Content-Security-Policy
  Content-Security-Policy: default-src 'none'; script-src blob:; connect-src 'none'; worker-src 'none'
`;

for (const [name, text] of Object.entries(out)) await writeFile(path.join(root, name), text);
console.log(`Wrote ${Object.keys(out).join(", ")} for ${site}`);
